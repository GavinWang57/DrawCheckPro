def html(app_name: str, version: str) -> str:
  parts = [f"<h2>{app_name} <span style='color:#8fa6c4;font-size:13px'>v{version}</span></h2>",
           f"<p>{INTRO}</p>"]
  for title, items in GUIDE:
    parts.append(f"<h3 style='color:#42a5f5;margin-bottom:4px'>{title}</h3>")
    bullets = [i[2:] for i in items if i.startswith("- ")]
    paras = [i for i in items if not i.startswith("- ")]
    parts.extend(f"<p>{p}</p>" for p in paras)
    if bullets:
      parts.append("<ul style='margin-top:0'>" + "".join(f"<li>{b}</li>" for b in bullets)
                   + "</ul>")
  parts.append("<h3 style='color:#42a5f5'>快捷鍵</h3><table cellspacing='0'>")
  for group, items in SHORTCUTS:
    parts.append(f"<tr><td colspan='2' style='padding-top:8px;color:#8fa6c4'><b>{group}</b></td></tr>")
    for key, desc in items:
      parts.append(f"<tr><td style='padding:2px 18px 2px 8px;white-space:nowrap'><b>{key}</b></td>"
                   f"<td>{desc}</td></tr>")
  parts.append("</table>")
  return "".join(parts)
